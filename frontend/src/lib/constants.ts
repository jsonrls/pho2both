/**
 * Computes a combined CSS filter string merging the base preset filter with manual adjustments
 */
export function buildCombinedCssFilter(
  filterId: FilterType,
  adj: ManualAdjustments
): string {
  const matched = FILTERS.find((f) => f.id === filterId);
  const baseCss = matched && matched.cssFilter !== "none" ? matched.cssFilter : "";

  const parts: string[] = [];
  if (baseCss) parts.push(baseCss);

  // 1. Exposure & Brightness
  const totalBrightness = 100 + adj.brightness + Math.round(adj.exposure * 0.7);
  if (totalBrightness !== 100) {
    parts.push(`brightness(${Math.max(10, totalBrightness)}%)`);
  }

  // 2. Contrast & Clarity
  const totalContrast = 100 + adj.contrast + Math.round(adj.clarity * 0.4);
  if (totalContrast !== 100) {
    parts.push(`contrast(${Math.max(10, totalContrast)}%)`);
  }

  // 3. Saturation & Vibrance
  const totalSat = 100 + adj.saturation + Math.round(adj.vibrance * 0.5);
  if (totalSat !== 100) {
    parts.push(`saturate(${Math.max(0, totalSat)}%)`);
  }

  // 4. Hue & Tint
  const totalHue = adj.hue + Math.round(adj.tint * 0.4);
  if (totalHue !== 0) {
    parts.push(`hue-rotate(${totalHue}deg)`);
  }

  // 5. Temperature (Warm sepia or cool shift)
  if (adj.temperature > 0) {
    parts.push(
      `sepia(${Math.round(adj.temperature * 0.35)}%) hue-rotate(${-Math.round(adj.temperature * 0.1)}deg)`
    );
  } else if (adj.temperature < 0) {
    parts.push(`hue-rotate(${Math.round(Math.abs(adj.temperature) * 1.2)}deg)`);
  }

  // 6. Blur
  if (adj.blur > 0) {
    parts.push(`blur(${(adj.blur * 0.1).toFixed(1)}px)`);
  }

  // 7. Fade (lifted blacks simulation via opacity & brightness blend)
  if (adj.fade > 0) {
    parts.push(`opacity(${Math.max(50, 100 - Math.round(adj.fade * 0.2))}%)`);
  }

  return parts.length > 0 ? parts.join(" ") : "none";
}

/**
 * Draws a photographic vignette onto a Canvas 2D context
 */
export function drawCanvasVignette(
  ctx: CanvasRenderingContext2D,
  w: number,
  h: number,
  intensity: number
) {
  if (intensity <= 0) return;
  const radial = ctx.createRadialGradient(
    w / 2,
    h / 2,
    Math.min(w, h) * 0.35,
    w / 2,
    h / 2,
    Math.max(w, h) * 0.72
  );
  radial.addColorStop(0, "rgba(0,0,0,0)");
  radial.addColorStop(1, `rgba(0,0,0,${Math.min(0.9, intensity * 0.009)})`);
  ctx.fillStyle = radial;
  ctx.fillRect(0, 0, w, h);
}

/**
 * Draws subtle analog film grain noise onto a Canvas 2D context
 */
export function drawCanvasGrain(
  ctx: CanvasRenderingContext2D,
  w: number,
  h: number,
  intensity: number
) {
  if (intensity <= 0) return;
  const grainCanvas = document.createElement("canvas");
  const gw = 120;
  const gh = 120;
  grainCanvas.width = gw;
  grainCanvas.height = gh;
  const gctx = grainCanvas.getContext("2d");
  if (!gctx) return;

  const imgData = gctx.createImageData(gw, gh);
  const data = imgData.data;
  const alpha = Math.min(120, Math.round(intensity * 1.2));
  for (let i = 0; i < data.length; i += 4) {
    const val = (Math.random() * 255) | 0;
    data[i] = val;
    data[i + 1] = val;
    data[i + 2] = val;
    data[i + 3] = (Math.random() * alpha) | 0;
  }
  gctx.putImageData(imgData, 0, 0);

  const pattern = ctx.createPattern(grainCanvas, "repeat");
  if (pattern) {
    ctx.save();
    ctx.globalCompositeOperation = "overlay";
    ctx.fillStyle = pattern;
    ctx.fillRect(0, 0, w, h);
    ctx.restore();
  }
}

